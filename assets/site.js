        function toggleLanguage() {

            currentLang = currentLang === 'en' ? 'ar' : 'en';

            document.documentElement.dir =
                currentLang === 'ar' ? 'rtl' : 'ltr';

            document.documentElement.lang = currentLang;
            document.getElementById('langToggleBtn').setAttribute('aria-label', currentLang === 'ar' ? 'EN — التبديل إلى الإنجليزية' : 'AR — Switch to Arabic');

            document.body.classList.toggle('lang-ar', currentLang === 'ar');

            document.getElementById('langLabel').textContent =
                currentLang === 'ar' ? 'EN' : 'AR';

            document.querySelectorAll('[data-i18n]').forEach(el => {

                const key = el.getAttribute('data-i18n');

                const value = projectCopy[currentLang][key] ?? i18n[currentLang][key];
                if (!value) return;

                if (el.tagName === 'P' || el.tagName === 'DIV') {
                    el.innerHTML = value;
                } else {
                    el.textContent = value;
                }
            });

            document.querySelectorAll('[data-i18n-aria-label]').forEach(el => {
                const key = el.getAttribute('data-i18n-aria-label');
                const label = key === 'modal_close'
                    ? modalCopy[currentLang].close
                    : (projectCopy[currentLang][key] ?? i18n[currentLang][key]);
                if (label) el.setAttribute('aria-label', label);
            });

            if (projectDialog.open) renderProjectDetails(currentModalKey);
            updateMenuLabel();
            typingEl.textContent = heroPhrases[currentLang][0];

            if (simulatorLoaded) recalcChurn();

            if (typeof window.updateNavSpy === 'function') {
                setTimeout(window.updateNavSpy, 60);
            }

            showToast(
                currentLang === 'ar'
                    ? 'تم التحويل إلى العربية'
                    : 'Switched to English'
            );
        }


