        function drawParticles() {

            ctx.clearRect(
                0,
                0,
                canvas.width,
                canvas.height
            );

            points.forEach(point => {

                if (backgroundMotion) {
                    point.pulse += 0.018;

                    if (backgroundPointer.active) {
                        const dx = backgroundPointer.x - point.x;
                        const dy = backgroundPointer.y - point.y;
                        const distance = Math.hypot(dx, dy);

                        if (distance < 190 && distance > 1) {
                            const force = (190 - distance) / 190 * 0.012;
                            point.vx += (dx / distance) * force;
                            point.vy += (dy / distance) * force;
                        }
                    }

                    point.vx *= 0.994;
                    point.vy *= 0.994;
                    point.x += point.vx;
                    point.y += point.vy;
                }

                if (
                    point.x < 0 ||
                    point.x > canvas.width
                ) {
                    point.vx *= -1;
                }

                if (
                    point.y < 0 ||
                    point.y > canvas.height
                ) {
                    point.vy *= -1;
                }

                const alpha = 0.2 + Math.sin(point.pulse) * 0.06;
                ctx.fillStyle = `rgba(244, 63, 94, ${alpha})`;
                ctx.beginPath();
                ctx.arc(point.x, point.y, point.r, 0, Math.PI * 2);
                ctx.fill();
            });

            for (let i = 0; i < points.length; i++) {
                for (let j = i + 1; j < points.length; j++) {
                    const a = points[i];
                    const b = points[j];
                    const distance = Math.hypot(a.x - b.x, a.y - b.y);
                    if (distance > 145) continue;

                    const opacity = (1 - distance / 145) * 0.18;
                    ctx.strokeStyle = `rgba(225, 29, 72, ${opacity})`;
                    ctx.lineWidth = 0.7;
                    ctx.beginPath();
                    ctx.moveTo(a.x, a.y);
                    ctx.lineTo(b.x, b.y);
                    ctx.stroke();
                }
            }

            if (backgroundPointer.active) {
                points.forEach(point => {
                    const distance = Math.hypot(backgroundPointer.x - point.x, backgroundPointer.y - point.y);
                    if (distance > 190) return;
                    ctx.strokeStyle = `rgba(244, 63, 94, ${(1 - distance / 190) * 0.34})`;
                    ctx.lineWidth = 1;
                    ctx.beginPath();
                    ctx.moveTo(backgroundPointer.x, backgroundPointer.y);
                    ctx.lineTo(point.x, point.y);
                    ctx.stroke();
                });
            }


        }




