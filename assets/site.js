        function showToast(msg) {

            const container =
                document.getElementById('toastContainer');

            const toast = document.createElement('div');

            toast.className =
                'glass-box px-4 py-2.5 rounded-xl border border-crimson/50 text-xs font-mono text-white shadow-2xl flex items-center gap-2 transform translate-y-3 opacity-0 transition-all duration-300';

            toast.innerHTML = `
                <i class="fa-solid fa-circle-check text-crimson"></i>
                <span>${msg}</span>
            `;

            container.appendChild(toast);

            requestAnimationFrame(() => {
                toast.classList.remove(
                    'translate-y-3',
                    'opacity-0'
                );
            });

            setTimeout(() => {

                toast.classList.add(
                    'opacity-0',
                    'translate-y-2'
                );

                setTimeout(() => {
                    toast.remove();
                }, 300);

            }, 2800);
        }


